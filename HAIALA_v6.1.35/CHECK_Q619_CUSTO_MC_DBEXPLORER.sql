WITH ELEGIVEL AS (
 SELECT G.CODGRUPOPROD FROM SANKHYA.TGFGRU G
 START WITH G.CODGRUPOPROD=40000000
 CONNECT BY NOCYCLE PRIOR G.CODGRUPOPROD=G.CODGRUPAI
), EXCECAO AS (
 SELECT G.CODGRUPOPROD FROM SANKHYA.TGFGRU G
 START WITH G.CODGRUPOPROD=40209000
 CONNECT BY NOCYCLE PRIOR G.CODGRUPOPROD=G.CODGRUPAI
), DEV_ITENS AS (
 SELECT C.NUNOTA, C.DTNEG, C.CODTIPOPER, I.SEQUENCIA, I.CODPROD,
        NVL(I.QTDNEG,0) AS QTD, NVL(I.VLRTOT,0)-NVL(I.VLRDESC,0)-NVL(I.VLRDESCRAT,0) AS VLC
 FROM SANKHYA.TGFCAB C
 JOIN SANKHYA.TGFTOP T ON T.CODTIPOPER=C.CODTIPOPER AND T.DHALTER=C.DHTIPOPER
 JOIN SANKHYA.TGFITE I ON I.NUNOTA=C.NUNOTA
 JOIN SANKHYA.TGFPRO P ON P.CODPROD=I.CODPROD
 WHERE C.CODEMP=1 AND C.TIPMOV='D' AND T.AD_GRUPO=5
 AND C.STATUSNOTA IN ('A','P','L')
 AND C.DTNEG>=DATE '2026-01-01'
 AND C.DTNEG<LEAST(TRUNC(SYSDATE)+1,DATE '2027-01-01')
 AND P.CODGRUPOPROD IN (SELECT CODGRUPOPROD FROM ELEGIVEL)
 AND P.CODGRUPOPROD NOT IN (SELECT CODGRUPOPROD FROM EXCECAO)
), VINCULOS AS (
 SELECT DISTINCT V.NUNOTA,V.SEQUENCIA,V.NUNOTAORIG,V.SEQUENCIAORIG
 FROM SANKHYA.TGFVAR V
 JOIN DEV_ITENS D ON D.NUNOTA=V.NUNOTA AND D.SEQUENCIA=V.SEQUENCIA
), CONFERENCIA AS (
 SELECT D.NUNOTA, D.SEQUENCIA, D.CODPROD, D.DTNEG, D.QTD, D.VLC,
        CASE WHEN NF.TIPMOV='V' AND NF.CODEMP=1 AND O.CODPROD=D.CODPROD THEN 1 ELSE 0 END AS VINCULO_VALIDO,
        CASE WHEN NF.TIPMOV='V' AND NF.CODEMP=1 AND O.CODPROD=D.CODPROD THEN O.QTDNEG END AS QTD_ORIG,
        CASE WHEN NF.TIPMOV='V' AND NF.CODEMP=1 AND O.CODPROD=D.CODPROD THEN CUS.CUSSEMICM END AS CUS_UNIT
 FROM DEV_ITENS D
 LEFT JOIN VINCULOS V ON V.NUNOTA=D.NUNOTA AND V.SEQUENCIA=D.SEQUENCIA
 LEFT JOIN SANKHYA.TGFITE O ON O.NUNOTA=V.NUNOTAORIG AND O.SEQUENCIA=V.SEQUENCIAORIG
 LEFT JOIN SANKHYA.TGFCAB NF ON NF.NUNOTA=O.NUNOTA
 OUTER APPLY (
  SELECT C.CUSSEMICM
  FROM SANKHYA.TGFCUS C
  WHERE C.CODPROD=O.CODPROD AND C.CODEMP=NF.CODEMP AND C.CUSSEMICM>0
  ORDER BY CASE WHEN C.DTATUAL<TRUNC(NF.DTNEG,'MM') THEN 0 ELSE 1 END,
           C.DTATUAL DESC, C.DHALTER DESC
  FETCH FIRST 1 ROW ONLY
 ) CUS
)
SELECT TO_CHAR(DTNEG,'YYYY-MM-DD') AS DIA, NUNOTA AS DOCUMENTO, CODPROD AS SKU,
       COUNT(DISTINCT SEQUENCIA) AS ITENS_DEV,
       ROUND(SUM(CASE WHEN RN=1 THEN QTD ELSE 0 END),6) AS QTD_DEV,
       ROUND(SUM(CASE WHEN RN=1 THEN VLC ELSE 0 END),2) AS VLC_DEV,
       SUM(VINCULO_VALIDO) AS VINCULOS_VALIDOS,
       SUM(CASE WHEN VINCULO_VALIDO=1 AND CUS_UNIT>0 THEN 1 ELSE 0 END) AS LINHAS_COM_CUSTO,
       SUM(CASE WHEN VINCULO_VALIDO=1 AND QTD>NVL(QTD_ORIG,0) THEN 1 ELSE 0 END) AS QTD_EXCEDE,
       ROUND(SUM(CASE WHEN VINCULO_VALIDO=1 AND CUS_UNIT>0 THEN QTD*CUS_UNIT ELSE 0 END),6) AS CUSTO_REF
FROM (
 SELECT X.*, ROW_NUMBER() OVER (PARTITION BY NUNOTA,SEQUENCIA ORDER BY VINCULO_VALIDO DESC) AS RN
 FROM CONFERENCIA X
)
GROUP BY TO_CHAR(DTNEG,'YYYY-MM-DD'),NUNOTA,CODPROD
ORDER BY DIA,DOCUMENTO,SKU
